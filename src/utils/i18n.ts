/**
 * Detects the user's location & browser settings to establish default language
 */
export function detectUserLanguage(): SupportedLanguage {
  if (typeof window === 'undefined') return 'en';
  
  // 1. Check existing saved preference in localStorage
  const saved = localStorage.getItem('autoapply_language') as SupportedLanguage;
  if (saved && TRANSLATIONS[saved]) {
    return saved;
  }

  // 2. Check browser navigator language
  const navLang = (navigator.language || (navigator as any).userLanguage || 'en').toLowerCase();
  
  if (navLang.startsWith('de')) return 'de';
  if (navLang.startsWith('es')) return 'es';
  if (navLang.startsWith('fr')) return 'fr';
  if (navLang.startsWith('ja')) return 'ja';
  if (navLang.startsWith('zh')) return 'zh';
  if (navLang.startsWith('hi')) return 'hi';
  if (navLang.startsWith('ar')) return 'ar';
  if (navLang.startsWith('pt')) return 'pt';
  if (navLang.startsWith('ru')) return 'ru';
  if (navLang.startsWith('it')) return 'it';
  if (navLang.startsWith('nl')) return 'nl';
  if (navLang.startsWith('ko')) return 'ko';
  if (navLang.startsWith('vi')) return 'vi';
  if (navLang.startsWith('id')) return 'id';
  if (navLang.startsWith('tr')) return 'tr';
  if (navLang.startsWith('pl')) return 'pl';
  if (navLang.startsWith('sv')) return 'sv';

  // 3. Fallback based on timezone heuristics
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone.toLowerCase();
    if (tz.includes('berlin') || tz.includes('vienna') || tz.includes('zurich')) return 'de';
    if (tz.includes('madrid') || tz.includes('mexico') || tz.includes('buenos_aires') || tz.includes('bogota')) return 'es';
    if (tz.includes('paris') || tz.includes('brussels') || tz.includes('quebec')) return 'fr';
    if (tz.includes('tokyo')) return 'ja';
    if (tz.includes('shanghai') || tz.includes('taipei') || tz.includes('hong_kong')) return 'zh';
    if (tz.includes('kolkata') || tz.includes('calcutta') || tz.includes('mumbai') || tz.includes('delhi')) return 'hi';
    if (tz.includes('dubai') || tz.includes('riyadh') || tz.includes('cairo')) return 'ar';
    if (tz.includes('sao_paulo') || tz.includes('lisbon')) return 'pt';
    if (tz.includes('moscow')) return 'ru';
    if (tz.includes('rome')) return 'it';
    if (tz.includes('amsterdam')) return 'nl';
    if (tz.includes('seoul')) return 'ko';
    if (tz.includes('saigon') || tz.includes('ho_chi_minh') || tz.includes('hanoi')) return 'vi';
    if (tz.includes('jakarta')) return 'id';
    if (tz.includes('istanbul')) return 'tr';
    if (tz.includes('warsaw')) return 'pl';
    if (tz.includes('stockholm')) return 'sv';
  } catch (e) {}

  return 'en';
}

/**
 * Returns translated string for given key in given language with English fallback
 */
export function getTranslation(lang: SupportedLanguage, key: string, params?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dictionary[key] || TRANSLATIONS.en[key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
